/**
 * Searches and returns pre-trained vehicle specifications matching brand and model.
 */
export function lookupPretrainedVehicle(brand: string, model: string): PretrainedVehicleSpec | null {
  const cleanBrand = brand.trim().toLowerCase();
  const cleanModel = model.trim().toLowerCase();

  return (
    PRETRAINED_VEHICLE_DATABASE.find(
      (v) =>
        v.brand.toLowerCase() === cleanBrand &&
        (v.model.toLowerCase() === cleanModel ||
          cleanModel.includes(v.model.toLowerCase()) ||
          v.model.toLowerCase().includes(cleanModel))
    ) || null
  );
}
